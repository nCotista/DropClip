import AppKit

/// The pasteboard calls DropClip needs: `NSPasteboard` in the app, a fake in
/// tests.
public protocol PasteboardSource: AnyObject {
    var changeCount: Int { get }
    var currentTypes: [NSPasteboard.PasteboardType] { get }
    func data(forType type: NSPasteboard.PasteboardType) -> Data?
    @discardableResult func clearContents() -> Int
    @discardableResult func setData(_ data: Data?, forType type: NSPasteboard.PasteboardType) -> Bool
}

extension NSPasteboard: PasteboardSource {
    public var currentTypes: [NSPasteboard.PasteboardType] { types ?? [] }
}

/// One clipboard representation, e.g. `text/plain` bytes.
public struct ClipItem: Equatable {
    public let mime: String
    public let data: Data

    public init(mime: String, data: Data) {
        self.mime = mime
        self.data = data
    }
}

/// `ClipSnapshot` of PROTO-DC-V2.0 §14.1.
public struct ClipSnapshot: Equatable {
    public let changeToken: Int
    public let isConcealed: Bool
    /// Always empty when concealed: the content is never read (§10.4).
    public let items: [ClipItem]
    /// Milliseconds since the Unix epoch.
    public let ts: Int64
}

public enum ClipboardFormats {
    /// §14.1 native formats and their pasteboard types, in reporting order.
    /// Converting between them is the Dart normalizer's job (§11), not ours.
    public static let all: [(mime: String, type: NSPasteboard.PasteboardType)] = [
        ("text/plain", .string),
        ("text/uri-list", .URL),
        ("image/png", .png),
        ("image/jpeg", NSPasteboard.PasteboardType("public.jpeg")),
        ("image/tiff", .tiff),
    ]

    /// §10.4 macOS markers (password managers, Keychain, auto-generated
    /// content). When any is present the content is never read.
    public static let concealed: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
    ]
}

/// `read` / `write` / `clear` / `changeToken` of the `dropclip/clipboard`
/// channel (§14.1, FR-03A).
public final class ClipboardAccess {
    private let pasteboard: PasteboardSource
    private let now: () -> Date

    public init(pasteboard: PasteboardSource, now: @escaping () -> Date = Date.init) {
        self.pasteboard = pasteboard
        self.now = now
    }

    /// macOS `changeCount`.
    public var changeToken: Int { pasteboard.changeCount }

    /// The current contents, or nil when the pasteboard holds nothing DropClip
    /// syncs. Concealed content is reported with no items and is never read.
    public func read() -> ClipSnapshot? {
        let types = Set(pasteboard.currentTypes)
        let token = pasteboard.changeCount
        let ts = Int64(now().timeIntervalSince1970 * 1000)
        if !types.isDisjoint(with: ClipboardFormats.concealed) {
            return ClipSnapshot(changeToken: token, isConcealed: true, items: [], ts: ts)
        }
        var items: [ClipItem] = []
        for format in ClipboardFormats.all where types.contains(format.type) {
            if let data = pasteboard.data(forType: format.type) {
                items.append(ClipItem(mime: format.mime, data: data))
            }
        }
        if items.isEmpty { return nil }
        return ClipSnapshot(changeToken: token, isConcealed: false, items: items, ts: ts)
    }

    /// Replaces the contents with all [items] at once and returns the new
    /// change token. Unknown MIME types are skipped.
    @discardableResult
    public func write(_ items: [ClipItem]) -> Int {
        pasteboard.clearContents()
        for item in items {
            guard let format = ClipboardFormats.all.first(where: { $0.mime == item.mime }) else {
                continue
            }
            pasteboard.setData(item.data, forType: format.type)
        }
        return pasteboard.changeCount
    }

    public func clear() {
        pasteboard.clearContents()
    }
}

/// Reports each pasteboard change once, by comparing `changeCount`.
public final class ClipboardWatcher {
    private let access: ClipboardAccess
    private var lastChangeCount: Int

    public init(access: ClipboardAccess) {
        self.access = access
        self.lastChangeCount = access.changeToken
    }

    /// The new contents since the last call, or nil if nothing new (or
    /// nothing DropClip syncs) was copied.
    public func poll() -> ClipSnapshot? {
        let count = access.changeToken
        guard count != lastChangeCount else { return nil }
        lastChangeCount = count
        return access.read()
    }
}
